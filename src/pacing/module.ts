import type { PacingResult } from "./engine.js";
import { buildPacingFormula, type PacingFormula } from "./formula.js";

/**
 * Emit a dependency-free ES module generated from the minimal formula basis.
 *
 * The module does NOT embed the result. It carries:
 *   - base rates + rate deltas (cumulative state is computed on call),
 *   - city/population step points,
 *   - indexed action/milestone tuples with shared ids/labels,
 *   - metadata.
 *
 * That keeps the artifact at ~O(changes + events) instead of O(turns × dims).
 * `--format=json` remains the full, exact result for consumers that need it.
 */

function payloadOf(formula: PacingFormula): string {
  return JSON.stringify(formula);
}

export function renderPacingModule(result: PacingResult): string {
  const formula = buildPacingFormula(result);
  const data = payloadOf(formula);
  const header = [
    "// generated by `npm run pace` — civi6.pacing/formula/v1 — do not edit",
    `// ${result.input.civId}${result.input.leaderId ? ` / ${result.input.leaderId}` : ""} · ${result.input.victoryId} · ${result.input.speed} · assurance=${result.input.assurance}`,
    '// state is computed from base+Δrate on call; actions/milestones from indexed event tuples.',
    '// usage: `import pace from "./file.mjs"; pace.science(120); pace.state(120).research`',
  ].join("\n");

  return `${header}
const F = ${data};
const T = F.T;
const STATE_KEYS = ${JSON.stringify(["science", "culture", "gold", "production", "food", "faith", "tourism"])};
const ACTION_KINDS = ${JSON.stringify(["research", "civic", "build", "district", "project", "unit", "settle"])};
const MILESTONE_KINDS = ${JSON.stringify(["tech", "civic", "building", "district", "project", "unit"])};
const MILESTONE_ROLES = ${JSON.stringify(["terminal", "enabler", "booster"])};
const CURRENCY = { tech: "science", civic: "culture", building: "production", district: "production", project: "production", unit: "production" };
const WHY = { terminal: "终局链", enabler: "前置/解锁", booster: "瓶颈产出" };

function normalizeTurn(t) {
  const n = Math.floor(Number(t));
  if (!Number.isFinite(n)) throw new TypeError("t 必须是数字");
  return n;
}

function clampTurn(n) {
  if (n < 1) return 0;
  return n > T ? T : n;
}

// Cumulative: base·n + Σ Δ·(n − turn + 1) for every rate change ≤ n.
function cumulativeAt(key, t) {
  const n = clampTurn(normalizeTurn(t));
  if (n <= 0) return 0;
  let value = F.base[key] * n;
  const changes = F.delta[key];
  for (let i = 0; i < changes.length; i++) {
    const turn = changes[i][0];
    if (turn > n) break;
    value += changes[i][1] * (n - turn + 1);
  }
  return value;
}

function rateAt(key, t) {
  const n = clampTurn(normalizeTurn(t));
  if (n <= 0) return 0;
  let value = F.base[key];
  const changes = F.delta[key];
  for (let i = 0; i < changes.length; i++) {
    if (changes[i][0] > n) break;
    value += changes[i][1];
  }
  return value;
}

function stepAt(key, t) {
  const n = clampTurn(normalizeTurn(t));
  if (n <= 0) return 0;
  const points = F.counts[key];
  let value = points.length ? points[0][1] : 0;
  for (let i = 0; i < points.length; i++) {
    if (points[i][0] > n) break;
    value = points[i][1];
  }
  return value;
}

function toAction(a) {
  return {
    from: a[0],
    to: a[1],
    kind: ACTION_KINDS[a[2]],
    id: F.ids[a[3]],
    label: F.labels[a[3]],
    count: a[4],
  };
}

function actionsAt(t) {
  const n = normalizeTurn(t);
  if (n < 1) return [];
  return F.actions.filter((a) => a[0] <= n && n <= a[1]).map(toAction);
}

function builds(t) {
  return actionsAt(t).filter(
    (a) => a.kind === "build" || a.kind === "district" || a.kind === "project" || a.kind === "unit",
  );
}

function actionRef(kind, t) {
  const n = normalizeTurn(t);
  if (n < 1) return null;
  const a = F.actions.find((x) => ACTION_KINDS[x[2]] === kind && x[0] <= n && n <= x[1]);
  return a ? { id: F.ids[a[3]], label: F.labels[a[3]] } : null;
}

function toMilestone(m) {
  const kind = MILESTONE_KINDS[m[2]];
  const latestTurn = m[1] < 0 ? null : m[1];
  const role = MILESTONE_ROLES[m[5]];
  return {
    turn: m[0],
    kind,
    id: F.ids[m[3]],
    labelZh: F.labels[m[3]],
    cost: m[4],
    currency: CURRENCY[kind] || null,
    role,
    latestTurn,
    slack: latestTurn === null ? null : latestTurn - m[0],
    why: WHY[role],
    city: m[6] || null,
    deps: [],
  };
}

function milestonesUntil(t) {
  const n = normalizeTurn(t);
  if (n < 1) return [];
  return F.milestones.filter((m) => m[0] <= n).map(toMilestone);
}

function nextMilestone(t) {
  const n = normalizeTurn(t);
  const m = F.milestones.find((x) => x[0] > n);
  return m ? toMilestone(m) : null;
}

function rate(t) {
  const n = normalizeTurn(t);
  const out = {};
  for (const key of STATE_KEYS) out[key] = rateAt(key, n);
  return out;
}

function state(t) {
  const n = normalizeTurn(t);
  const cumulative = {};
  const rates = {};
  for (const key of STATE_KEYS) {
    cumulative[key] = cumulativeAt(key, n);
    rates[key] = rateAt(key, n);
  }
  return {
    turn: n,
    cumulative,
    rate: rates,
    cities: stepAt("cities", n),
    population: stepAt("population", n),
    research: actionRef("research", n),
    civic: actionRef("civic", n),
    builds: builds(n),
  };
}

const science = (t) => cumulativeAt("science", t);
const culture = (t) => cumulativeAt("culture", t);
const gold = (t) => cumulativeAt("gold", t);
const production = (t) => cumulativeAt("production", t);
const food = (t) => cumulativeAt("food", t);
const faith = (t) => cumulativeAt("faith", t);
const tourism = (t) => cumulativeAt("tourism", t);
const cities = (t) => stepAt("cities", t);
const population = (t) => stepAt("population", t);
const research = (t) => actionRef("research", t);
const civic = (t) => actionRef("civic", t);
const rateOf = (key, t) => rateAt(key, t);

const api = Object.freeze({
  T,
  science,
  culture,
  gold,
  production,
  food,
  faith,
  tourism,
  cities,
  population,
  rate,
  rateOf,
  state,
  research,
  civic,
  builds,
  actionsAt,
  milestonesUntil,
  nextMilestone,
  formula: F,
  input: F.meta.input,
  basis: F.meta.basis,
  baseline: F.meta.baseline,
  checks: F.meta.checks,
  assumptions: F.meta.assumptions,
});

export {
  T,
  science,
  culture,
  gold,
  production,
  food,
  faith,
  tourism,
  cities,
  population,
  rate,
  rateOf,
  state,
  research,
  civic,
  builds,
  actionsAt,
  milestonesUntil,
  nextMilestone,
};
export default api;
`;
}
